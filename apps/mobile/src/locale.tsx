export type CopyKey = keyof typeof strings.en;
const initialLocale = (): Locale => {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.startsWith("fr")
      ? "fr"
      : "en";
  } catch {
    return "en";
  }
};
function value(locale: Locale, setLocale: (locale: Locale) => void) {
  return {
    locale,
    setLocale,
    t: (key: string) =>
      strings[locale][key as CopyKey] ?? strings.en[key as CopyKey] ?? key,
    money: (amount: number) =>
      new Intl.NumberFormat(locale === "fr" ? "fr-CM" : "en-CM", {
        maximumFractionDigits: 0,
      }).format(amount),
    date: (input: string) =>
      new Intl.DateTimeFormat(locale === "fr" ? "fr-CM" : "en-CM", {
        day: "numeric",
        month: "long",
        year: "numeric",
        timeZone: "UTC",
      }).format(new Date(input.length === 10 ? `${input}T12:00:00Z` : input)),
  };
}
const LocaleContext = createContext(value("en", () => {}));
export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);
  const state = useMemo(() => value(locale, setLocale), [locale]);
  return (
    <LocaleContext.Provider value={state}>{children}</LocaleContext.Provider>
  );
}
export function useLocale() {
  return useContext(LocaleContext);
}
